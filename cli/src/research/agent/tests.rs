/// A stand-in research workspace on loopback: `reply` answers each request
/// (method, path, body) with a status and the reply's JSON, and every
/// request is kept (with its authorization).
struct Workspace {
    base: String,
    requests: Requests,
}

/// Each request: method, path, body and authorization.
type Requests = Arc<Mutex<Vec<(String, String, Value, Option<String>)>>>;

fn workspace(reply: impl Fn(&str, &str, &Value) -> (u16, Value) + Send + 'static) -> Workspace {
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let base = format!("http://127.0.0.1:{}", listener.local_addr().unwrap().port());
    let requests = Arc::new(Mutex::new(Vec::new()));
    let seen = requests.clone();
    std::thread::spawn(move || {
        for stream in listener.incoming() {
            let Ok(mut stream) = stream else { continue };
            let mut reader = BufReader::new(stream.try_clone().unwrap());
            let mut line = String::new();
            reader.read_line(&mut line).unwrap();
            let mut parts = line.split_whitespace();
            let (method, path) = (
                parts.next().unwrap_or_default().to_string(),
                parts.next().unwrap_or_default().to_string(),
            );
            let (mut length, mut authorization) = (0, None);
            loop {
                let mut header = String::new();
                reader.read_line(&mut header).unwrap();
                if header.trim().is_empty() {
                    break;
                }
                let (name, value) = header.split_once(':').unwrap();
                match name.to_ascii_lowercase().as_str() {
                    "content-length" => length = value.trim().parse().unwrap(),
                    "authorization" => authorization = Some(value.trim().to_string()),
                    _ => {}
                }
            }
            let mut body = vec![0; length];
            reader.read_exact(&mut body).unwrap();
            let body: Value = serde_json::from_slice(&body).unwrap_or(Value::Null);
            let (status, data) = reply(&method, &path, &body);
            seen.lock()
                .unwrap()
                .push((method, path, body, authorization));
            let text = data.to_string();
            let _ = write!(
                stream,
                "HTTP/1.1 {status} Reply\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{text}",
                text.len()
            );
        }
    });
    Workspace { base, requests }
}

fn ok(data: Value) -> (u16, Value) {
    (200, json!({ "ok": true, "data": data }))
}

fn refused(status: u16, code: &str, message: &str) -> (u16, Value) {
    (
        status,
        json!({ "ok": false, "error": { "code": code, "message": message } }),
    )
}

fn client(scratch: &Scratch, base: &str) -> AgentClient {
    let profiles = scratch.0.join("profiles");
    AgentClient::new(
        "cedar",
        "Codex",
        Some(base),
        Some(profiles.to_str().unwrap()),
    )
    .unwrap()
}

fn profile(scratch: &Scratch) -> Value {
    serde_json::from_slice(&fs::read(scratch.0.join("profiles").join("cedar.json")).unwrap())
        .unwrap()
}

#[test]
fn login_pairs_saves_a_private_profile_and_never_outputs_credentials() {
    let scratch = Scratch::new();
    let credential = token();
    let approved = Arc::new(Mutex::new(false));
    let (state, secret) = (approved.clone(), credential.clone());
    let server = workspace(move |method, path, _| match (method, path) {
        ("POST", "/v1/login") => ok(
            json!({ "pairingId": "12".repeat(16), "secret": "34".repeat(32), "userCode": "ABCD-1234", "expiresAt": 1_900_000_000_000_u64 }),
        ),
        ("POST", "/v1/login/poll") if !*state.lock().unwrap() => {
            ok(json!({ "status": "pending", "expiresAt": 1_900_000_000_000_u64 }))
        }
        ("POST", "/v1/login/poll") => ok(
            json!({ "status": "approved", "credential": secret, "agent": { "id": "agent-1", "name": "cedar" } }),
        ),
        ("GET", "/v1/me") => ok(json!({ "agent": { "id": "agent-1", "name": "cedar" } })),
        ("POST", "/v1/sessions") => ok(json!({ "session": { "id": "session-1" } })),
        ("POST", "/v1/sessions/heartbeat") => ok(json!({ "session": { "id": "session-1" } })),
        _ => refused(404, "NOT_FOUND", "Route not found."),
    });
    let agent = client(&scratch, &server.base);
    let pending = agent.login().unwrap();
    assert_eq!(pending["status"], "pending");
    assert_eq!(pending["userCode"], "ABCD-1234");
    assert!(pending.get("secret").is_none() && pending.get("credential").is_none());
    let saved = profile(&scratch);
    assert_eq!(saved["pending"]["pairingId"], "12".repeat(16));
    assert!(saved.get("loginAttempt").is_none());
    // Asking again before the owner approves: still pending, same pairing.
    let waiting = agent.login().unwrap();
    assert_eq!(waiting["status"], "pending");
    assert_eq!(
        waiting["nextStep"],
        "Ask the owner to approve this code in Petri\u{2019}s Connect view."
    );
    assert_eq!(waiting["error"], Value::Null);
    *approved.lock().unwrap() = true;
    let connected = agent.login().unwrap();
    assert_eq!(connected["status"], "connected");
    assert_eq!(connected["session"]["id"], "session-1");
    assert!(!connected.to_string().contains(&credential));
    let saved = profile(&scratch);
    assert_eq!(saved["credential"], credential);
    assert_eq!(
        (saved["agentId"].as_str(), saved["sessionId"].as_str()),
        (Some("agent-1"), Some("session-1"))
    );
    assert!(saved.get("pending").is_none());
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mode = fs::metadata(scratch.0.join("profiles").join("cedar.json"))
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o600);
    }
    // Logged in: the next login resumes the identity and its session.
    assert_eq!(agent.login().unwrap()["agent"]["id"], "agent-1");
    let requests = server.requests.lock().unwrap();
    let first = &requests[0];
    assert_eq!(
        (
            first.1.as_str(),
            first.2["name"].as_str(),
            first.2["harness"].as_str()
        ),
        ("/v1/login", Some("cedar"), Some("Codex"))
    );
    assert!(
        first.2["loginKey"]
            .as_str()
            .is_some_and(|key| key.len() == 64)
    );
    assert!(first.3.is_none(), "a pairing request carries no credential");
    let me = requests.iter().find(|r| r.1 == "/v1/me").unwrap();
    assert_eq!(
        me.3.as_deref(),
        Some(format!("Bearer {credential}").as_str())
    );
    // A heartbeat kept the saved session rather than opening another.
    assert_eq!(requests.iter().filter(|r| r.1 == "/v1/sessions").count(), 1);
    assert!(requests.iter().any(|r| r.1 == "/v1/sessions/heartbeat"));
}

#[test]
fn a_lost_login_response_retries_with_the_same_key() {
    let scratch = Scratch::new();
    let calls = Arc::new(Mutex::new(0));
    let count = calls.clone();
    let server = workspace(move |_, path, _| {
        let mut calls = count.lock().unwrap();
        *calls += 1;
        match (path, *calls) {
            ("/v1/login", 1) => refused(
                500,
                "INTERNAL_ERROR",
                "The workspace could not complete this request.",
            ),
            ("/v1/login", _) => ok(
                json!({ "pairingId": "ab".repeat(16), "secret": "cd".repeat(32), "userCode": "WXYZ-0000" }),
            ),
            _ => refused(404, "NOT_FOUND", "Route not found."),
        }
    });
    let agent = client(&scratch, &server.base);
    let error = agent.login().unwrap_err();
    assert_eq!(
        (error.code.as_deref(), error.status),
        (Some("INTERNAL_ERROR"), Some(500))
    );
    let key = profile(&scratch)["loginAttempt"]["loginKey"].clone();
    assert_eq!(agent.login().unwrap()["status"], "pending");
    let requests = server.requests.lock().unwrap();
    assert_eq!(requests[0].2["loginKey"], key);
    assert_eq!(requests[1].2["loginKey"], key);
}

#[test]
fn an_expired_session_opens_a_new_one_and_reports_are_checked_first() {
    let scratch = Scratch::new();
    let server = workspace(|_, path, body| match path {
        "/v1/sessions/heartbeat" => refused(401, "SESSION_EXPIRED", "This session expired."),
        "/v1/sessions" => ok(json!({ "session": { "id": "session-2" } })),
        "/v1/runs/run%201%2F2/events" => {
            ok(json!({ "event": { "kind": body["kind"], "sessionId": body["sessionId"] } }))
        }
        _ => refused(404, "NOT_FOUND", "Route not found."),
    });
    let profiles = private_directory(&scratch.0.join("profiles")).unwrap();
    private_write(&profiles.join("cedar.json"), &json!({ "version": 1, "name": "cedar", "baseUrl": server.base, "credential": token(), "sessionId": "session-1" })).unwrap();
    let agent = client(&scratch, &server.base);
    let report = |kind| Report {
        kind,
        message: Some("Read the listing."),
        reference_url: Some(""),
        client_key: Some("k-1"),
    };
    let refused = agent
        .report("run 1/2", report(Some("directive")))
        .unwrap_err();
    assert_eq!(refused.code.as_deref(), Some("INVALID_EVENT"));
    assert_eq!(
        refused.message,
        format!("Report one of: {}.", REPORT_KINDS.join(", "))
    );
    assert!(
        server.requests.lock().unwrap().is_empty(),
        "nothing is sent for a refused report"
    );
    let event = agent.report("run 1/2", report(None)).unwrap();
    assert_eq!(
        (
            event["event"]["kind"].as_str(),
            event["event"]["sessionId"].as_str()
        ),
        (Some("note"), Some("session-2"))
    );
    assert_eq!(profile(&scratch)["sessionId"], "session-2");
    let requests = server.requests.lock().unwrap();
    let sent = &requests.last().unwrap().2;
    assert_eq!(sent["clientKey"], "k-1");
    assert!(
        sent.get("referenceUrl").is_none(),
        "an empty source is left out"
    );
}

