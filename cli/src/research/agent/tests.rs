    assert_eq!(send(1, "tools/list", Value::Null)["error"]["code"], -32002);
    let init = send(2, "initialize", json!({ "protocolVersion": "2025-06-18" }));
    assert_eq!(init["result"]["protocolVersion"], "2025-06-18");
    assert_eq!(init["result"]["serverInfo"]["name"], "petri-research");
