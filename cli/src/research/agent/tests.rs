/// A fresh folder in the system's temporary folder, removed afterwards.
struct Scratch(PathBuf);
impl Scratch {
    fn new() -> Self {
        let path = std::env::temp_dir().join(format!("petri-agent-test-{}", &token()[..16]));
        fs::create_dir(&path).unwrap();
        Self(path)
    }
}
impl Drop for Scratch {
    fn drop(&mut self) {
        assert!(
            self.0
                .file_name()
                .unwrap()
                .to_string_lossy()
                .starts_with("petri-agent-test-")
        );
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn flags(values: &[(&str, &str)]) -> Flags {
    let mut flags = Flags::default();
    for (key, value) in values {
        flags.values.insert(key.to_string(), value.to_string());
    }
    flags
}

/// The Node workspace client's steps (research/client/steps.mjs, which
/// this replaced in 2026-10) for 20 replies, `own` being `'PETRI'`: generated by it, the
/// same text here.
#[cfg(unix)]
#[test]
fn work_next_steps_match_the_node_client_word_for_word() {
    let cases: Value = serde_json::from_str(include_str!("steps-fixtures.json")).unwrap();
    for case in cases.as_array().unwrap() {
        let mut values = Flags::default();
        for (key, value) in case["flags"].as_object().unwrap() {
            values
                .values
                .insert(key.clone(), value.as_str().unwrap().into());
        }
        let actual = super::steps::assignment_steps(case["reply"].clone(), &values, "'PETRI'");
        let expected = &case["expected"];
        if &actual != expected {
            let (a, e) = (
                actual["nextStep"].as_str().unwrap_or_default(),
                expected["nextStep"].as_str().unwrap_or_default(),
            );
            for (line, (a, e)) in a.lines().zip(e.lines()).enumerate() {
                assert_eq!(a, e, "{}: line {line}", case["name"]);
            }
            assert_eq!(&actual, expected, "{}", case["name"]);
        }
    }
}

