#[test]
fn a_bundle_goes_with_its_candidate_byte_for_byte_and_more_than_2_mib_is_refused_first() {
    let scratch = Scratch::new();
    let server = workspace(|_, path, _| match path {
        "/v1/sessions/heartbeat" => ok(json!({ "session": { "id": "session-1" } })),
        _ => ok(json!({ "duplicate": false })),
    });
    let profiles = private_directory(&scratch.0.join("profiles")).unwrap();
    private_write(&profiles.join("cedar.json"), &json!({ "version": 1, "name": "cedar", "baseUrl": server.base, "credential": token(), "sessionId": "session-1" })).unwrap();
    let agent = client(&scratch, &server.base);
    let head = br#"{"format":"amoeba-evidence-bundle-v1","presentation":""#;
    let tail = b"\"}\n";
    let mut bytes = head.to_vec();
    bytes.resize(MAX_BUNDLE_BYTES as usize - tail.len(), b'A');
    bytes.extend_from_slice(tail);
    let file = scratch.0.join("bundle.json");
    fs::write(&file, &bytes).unwrap();
    let candidate = json!({ "marketId": "ramx", "canonicalUrl": "https://portal.distributor.example/api/prices" });
    agent
        .submit(
            "run-1",
            &candidate,
            Some("proven"),
            Some(file.to_str().unwrap()),
        )
        .unwrap();
    let sent = server.requests.lock().unwrap().last().unwrap().2.clone();
    let mut keys: Vec<_> = sent.as_object().unwrap().keys().cloned().collect();
    keys.sort();
    assert_eq!(
        keys,
        ["candidate", "clientKey", "evidenceBundle", "sessionId"]
    );
    use base64::Engine as _;
    let decoded = base64::engine::general_purpose::STANDARD
        .decode(sent["evidenceBundle"].as_str().unwrap())
        .unwrap();
    assert!(decoded == bytes);
    let sent_before = server.requests.lock().unwrap().len();
    bytes.push(b' ');
    fs::write(&file, &bytes).unwrap();
    let not_bundle = scratch.0.join("candidate.json");
    fs::write(&not_bundle, candidate.to_string()).unwrap();
    for (path, code) in [
        (file.clone(), "BUNDLE_TOO_LARGE"),
        (not_bundle, "INVALID_BUNDLE"),
        (scratch.0.join("missing.json"), "BUNDLE_NOT_FOUND"),
    ] {
        let error = agent
            .submit(
                "run-1",
                &candidate,
                Some("again"),
                Some(path.to_str().unwrap()),
            )
            .unwrap_err();
        assert_eq!(error.code.as_deref(), Some(code), "{}", path.display());
    }
    assert_eq!(
        server.requests.lock().unwrap().len(),
        sent_before,
        "nothing is sent for a refused bundle"
    );
    assert_eq!(
        read_bundle_file(" ").unwrap_err().code.as_deref(),
        Some("INVALID_BUNDLE")
    );
    assert!(read_bundle_file(Path::new(&scratch.0).to_str().unwrap()).is_err());
}

/// A stand-in agent for the MCP server: what it was asked, and its answers.
#[derive(Default)]
struct Fake {
    calls: Mutex<Vec<Value>>,
}
impl Fake {
    fn record(&self, call: Value) -> Result<Value, Failure> {
        self.calls.lock().unwrap().push(call);
        Ok(json!({ "duplicate": false }))
    }
}
impl Agent for Fake {
    fn login(&self) -> Result<Value, Failure> {
        Ok(json!({ "status": "pending", "userCode": "CODE-TEST" }))
    }
    fn me(&self) -> Result<Value, Failure> {
        Err(fail("UNUSED", "Not in these tests."))
    }
    fn open_session(&self) -> Result<Value, Failure> {
        Err(Failure {
            code: None,
            message: "an internal detail".into(),
            status: None,
        })
    }
    fn close_session(&self) -> Result<Value, Failure> {
        Err(fail("SESSION_CLOSED", "No session is open."))
    }
    fn list_work(&self) -> Result<Value, Failure> {
        Ok(json!({ "work": [] }))
    }
    fn next(&self) -> Result<Value, Failure> {
        Ok(json!({ "status": "idle" }))
    }
    fn activity(&self) -> Result<Value, Failure> {
        Ok(json!({ "events": [] }))
    }
    fn rewards(&self) -> Result<Value, Failure> {
        Ok(json!({ "outcomes": [] }))
    }
    fn start_work(&self, work_id: &str, client_key: Option<&str>) -> Result<Value, Failure> {
        self.record(json!(["start", work_id, client_key]))
    }
    fn report(&self, run_id: &str, report: Report) -> Result<Value, Failure> {
        self.record(json!([
            "report",
            run_id,
            report.kind,
            report.message,
            report.reference_url,
            report.client_key
        ]))
    }
    fn submit(
        &self,
        run_id: &str,
        candidate: &Value,
        client_key: Option<&str>,
        bundle: Option<&str>,
    ) -> Result<Value, Failure> {
        self.record(json!(["submit", run_id, candidate, client_key, bundle]))
    }
    fn finish(&self, run_id: &str, summary: Option<&str>) -> Result<Value, Failure> {
        self.record(json!(["finish", run_id, summary]))
    }
}

fn session<'a>(fake: &'a Fake, flags: &'a Flags) -> impl FnMut(u64, &str, Value) -> Value + 'a {
    let mut handler = mcp::Handler::new(fake, flags, "'PETRI'".into());
    move |id, method, params| {
        handler
            .handle(&json!({ "jsonrpc": "2.0", "id": id, "method": method, "params": params }))
            .unwrap()
    }
}

